"""Canonical Pydantic v2 schemas for SpecGuard.

Defines the core data contracts between the Orchestrator, Git/MCP adapters,
RAG indexing service, LLM analysis engine, and Dispute resolution workflow.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


class ViolationSeverity(str, Enum):
    """Severity of a detected specification violation (FR-008, AC-005)."""
    CONFIRMED = "CONFIRMED"
    SUSPECTED = "SUSPECTED"


class RequirementStatus(str, Enum):
    """Evaluation status of a specification requirement (FR-004)."""
    IMPLEMENTED = "IMPLEMENTED"
    VIOLATED = "VIOLATED"
    NOT_AFFECTED = "NOT_AFFECTED"


class DisputeStatus(str, Enum):
    """Outcome status of a dispute review procedure (FR-012, AC-008)."""
    UPHELD = "UPHELD"
    OVERTURNED = "OVERTURNED"
    ACCEPTED = "ACCEPTED"
    REJECTED = "REJECTED"
    MODIFIED = "MODIFIED"


class SpecRequirement(BaseModel):
    """Structured requirement extracted from technical specification documents."""
    model_config = ConfigDict(populate_by_name=True)

    req_id: str
    section: str = ""
    title: str = ""
    description: str
    conditions: List[str] = Field(default_factory=list)
    exceptions: List[str] = Field(default_factory=list)
    raw_text: str = ""
    source_file: str = ""
    related_req_ids: List[str] = Field(default_factory=list)


class Evidence(BaseModel):
    """Concrete proof linking code changes with specification requirements."""
    model_config = ConfigDict(populate_by_name=True)

    file_path: str
    revision: str
    line_start: Optional[int] = None
    line_end: Optional[int] = None
    code_quote: str = ""
    spec_quote: str = ""


class Finding(BaseModel):
    """Audit verdict and evidence for a specific requirement."""
    model_config = ConfigDict(populate_by_name=True)

    req_id: str
    title: str
    status: RequirementStatus
    severity: Optional[ViolationSeverity] = None
    description: str
    evidence: List[Evidence] = Field(default_factory=list)
    counter_evidence: List[Evidence] = Field(default_factory=list)
    limitations: List[str] = Field(default_factory=list)


class FileChange(BaseModel):
    """File modification metadata from Git/MCP context."""
    model_config = ConfigDict(populate_by_name=True)

    filename: str
    status: str
    old_path: Optional[str] = None
    new_path: Optional[str] = None
    patch: Optional[str] = None
    is_truncated: bool = False


class GitContext(BaseModel):
    """Collected Git changes and provenance for a PR or commit audit."""
    model_config = ConfigDict(populate_by_name=True)

    target_repo: str
    target_ref: str
    base_sha: Optional[str] = None
    head_sha: str
    is_merge_commit: bool = False
    first_parent_sha: Optional[str] = None
    files: List[FileChange] = Field(default_factory=list)
    limitations: List[str] = Field(default_factory=list)
    is_partial: bool = False


class AuditReport(BaseModel):
    """Canonical audit report generated by SpecGuard Orchestrator."""
    model_config = ConfigDict(populate_by_name=True)

    audit_id: str
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )
    target_repo: str
    target_ref: str
    base_parent_sha: Optional[str] = None
    user_summary: str = ""
    language: str = "ru"
    findings: List[Finding] = Field(default_factory=list)
    limitations: List[str] = Field(default_factory=list)
    missing_data: List[str] = Field(default_factory=list)
    is_partial: bool = False
    metadata: Dict[str, Any] = Field(default_factory=dict)


class DisputeRequest(BaseModel):
    """User request to re-evaluate a specific audit finding."""
    model_config = ConfigDict(populate_by_name=True)

    audit_id: str
    finding_req_id: str
    user_comment: str


class DisputeResponse(BaseModel):
    """Re-evaluated audit verdict based on saved audit artifacts."""
    model_config = ConfigDict(populate_by_name=True)

    audit_id: str
    finding_req_id: str
    original_status: RequirementStatus
    original_severity: Optional[ViolationSeverity] = None
    dispute_status: str
    updated_finding: Finding
    reasoning: str
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )
